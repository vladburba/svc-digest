#!/usr/bin/env python3
"""Ключ дедупликации, устойчивый к переезду статьи.

Отдельный модуль без зависимостей намеренно: этой функцией пользуются и
`collect` (когда заводит запись), и `database` (когда доливает ключи старым
записям при миграции). Общий модуль убирает импорт тяжёлого collect с его
feedparser и httpx внутрь слоя базы.

ЗАЧЕМ ЭТО ВООБЩЕ. 2026-08-11 в один дайджест пришли две одинаковые новости на
позициях 5 и 6. Оказалось, Habr переносит статью между корпоративными блогами,
и её URL меняется:

    https://habr.com/ru/companies/yandex_cloud_and_infra/articles/1068692/
    https://habr.com/ru/companies/yandex/articles/1068692/

Ключом дедупа был guid из ленты, то есть ссылка. Сменилась ссылка — запись
выглядит новой, и статья приходит второй раз. Номер статьи при этом не
меняется НИКОГДА: он и есть настоящий идентификатор.

Проверено на боевой базе: 462 записи схлопываются в 458 — ловит ровно четыре
известные пары и не склеивает ничего лишнего (454 группы остались по одной).
"""

import re
from urllib.parse import urlparse

# Хабр и всё, что живёт на том же движке: путь вида /articles/<номер>/.
# Номер стабилен, всё что вокруг него — блог, компания, язык — может меняться.
ARTICLE_ID = re.compile(r"/articles/(\d+)")


def dedup_key(key, link=""):
    """Ключ «та же самая статья» для записи ленты.

    Три уровня, от надёжного к общему:
      1. номер статьи в пути → `habr.com:1068692` — переживает переезд блога;
      2. хост + путь без хвоста → отсекает UTM-метки, они у Habr в каждой ссылке;
      3. исходная строка — для лент, у которых guid вообще не URL.

    Хост нормализуем к нижнему регистру и без `www.`: одна и та же статья,
    отданная лентой как `Habr.com` и `www.habr.com`, обязана дать один ключ.
    """
    src = (key or link or "").strip()
    if not src:
        return ""

    parsed = urlparse(src)
    host = parsed.netloc.lower().removeprefix("www.")

    match = ARTICLE_ID.search(parsed.path or src)
    if match and host:
        return f"{host}:{match.group(1)}"

    if host:
        return f"{host}{(parsed.path or '').rstrip('/')}"

    return src
